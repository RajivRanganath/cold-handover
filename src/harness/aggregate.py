"""Build results/ from measured runs (M-*). Reads evidence only; changes nothing in runs/."""
import json, re, statistics
from pathlib import Path

W = Path("/path/to/tms-work")
OUT = W / "results"
OUT.mkdir(exist_ok=True)


def meta(path: Path) -> dict:
    d = {}
    for line in path.read_text().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            d.setdefault(k.split()[0], v)
    for line in path.read_text().splitlines():  # first line holds several k=v pairs
        for k, v in re.findall(r"(\w+)=(\S+)", line):
            d.setdefault(k, v)
    return d


rows = []
SCHEDULE = (W / "protocol/schedule.txt").read_text() + "\n" + (W / "protocol-r2/schedule.txt").read_text()  # round 1 + round 2
for label in [l.split()[1] for l in SCHEDULE.split("\n") if l.strip()]:
    a = W / "runs" / label
    r = {"label": label, "task": label.split("-")[1]}
    if not (a / "meta.txt").exists():
        r["outcome"] = "MISSING"
        rows.append(r)
        continue
    m = meta(a / "meta.txt")
    res = json.loads(m.get("result", "null")) if m.get("result", "unavailable") != "unavailable" else None
    usage = json.loads(m["usage"]) if m.get("usage", "unavailable") != "unavailable" else None
    tools = json.loads(m.get("tool_calls", "{}"))
    ev = json.loads((a / "eval.json").read_text()) if (a / "eval.json").exists() else None
    r.update(
        start=m.get("start"), wall_s=int(m.get("wall_s", 0)), agent_exit=m.get("agent_exit"),
        timeout=m.get("outcome_hint") == "TIMEOUT", api_retries=int((m.get("api_retries") or "0").split()[0]),
        credential_leak=m.get("credential_leak_files"), tool_calls=sum(tools.values()),
        turns=res and res.get("num_turns"), cost_usd_list=res and res.get("total_cost_usd"),
        output_tokens=usage and usage.get("output_tokens"),
        input_side_tokens=usage and sum(usage.get(k, 0) for k in ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens")),
        checks=ev and ev.get("checks"), failed_checks=ev and [k for k, v in ev["checks"].items() if not v],
    )
    if r["tool_calls"] == 0 and r["agent_exit"] != "0":
        r["outcome"] = "INVALID"
    elif r["timeout"]:
        r["outcome"] = "TIMEOUT"
    else:
        r["outcome"] = "PASS" if ev and ev.get("pass") else "FAIL"
    rows.append(r)

(OUT / "attempts.json").write_text(json.dumps(rows, indent=2) + "\n")

lines = ["# Measured results: baseline handover audit (round 1: T1-T3, round 2: T4)", "",
         "Generated by harness/aggregate.py from runs/M-*/ (meta.txt, eval.json). Model claude-haiku-5-5, original documentation only.", ""]
for t in ("T1", "T2", "T3", "T4"):
    rs = [r for r in rows if r["task"] == t]
    passed = sum(r["outcome"] == "PASS" for r in rs)
    walls = [r["wall_s"] for r in rs if r.get("wall_s")]
    lines += [f"## {t}: {passed} of {len(rs)} passed", "",
              "| Attempt | Outcome | Failed checks | Wall s | Tool calls | Output tokens | API retries | List-price $ |",
              "|---|---|---|---|---|---|---|---|"]
    for r in sorted(rs, key=lambda r: r["label"]):
        lines.append(f"| {r['label']} | {r['outcome']} | {', '.join(r.get('failed_checks') or []) or '-'} | {r.get('wall_s','')} | "
                     f"{r.get('tool_calls','')} | {r.get('output_tokens','')} | {r.get('api_retries','')} | {(r.get('cost_usd_list') or 0):.3f} |")
    if walls:
        lines += ["", f"Wall time: median {statistics.median(walls):.0f} s, range {min(walls)}–{max(walls)} s. Tool calls median {statistics.median([r['tool_calls'] for r in rs]):.0f}. API retries total {sum(r['api_retries'] for r in rs)}.", ""]
leaks = [r["label"] for r in rows if r.get("credential_leak") not in (None, "none")]
lines += ["## Integrity", "", f"Credential leaks: {', '.join(leaks) if leaks else 'none in any attempt'}.",
          f"Total list-price estimate: ${sum(r.get('cost_usd_list') or 0 for r in rows):.3f} (not billed; subscription usage).", ""]
(OUT / "results.md").write_text("\n".join(lines))
print("\n".join(lines))
